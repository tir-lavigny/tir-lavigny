<?php

namespace Tests\Unit;

use App\Models\Event;
use App\Models\EventChain;
use App\Services\EventChainGeneratorService;
use App\Services\EventChainUpdaterService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class EventChainServiceTest extends TestCase
{
    use RefreshDatabase;

    // ─── Generator ────────────────────────────────────────────────────────────

    public function test_generator_creates_events_for_each_occurrence(): void
    {
        // Create a daily chain spanning 3 days.
        // The EventChainObserver fires on creation and calls generate() automatically.
        $chain = EventChain::factory()->create([
            'recurrence_type' => 'daily',
            'start_date' => '2099-06-01',
            'end_date' => '2099-06-03',
            'start_time' => '09:00:00',
            'end_time' => '10:00:00',
            'interval' => 1,
        ]);

        // 3 daily occurrences should have been generated by the observer
        $this->assertEquals(3, $chain->events()->count());
    }

    public function test_generator_sets_correct_start_datetime(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create([
            'recurrence_type' => 'daily',
            'start_date' => '2099-07-01',
            'end_date' => '2099-07-01',
            'start_time' => '14:30:00',
            'end_time' => null,
        ]);

        app(EventChainGeneratorService::class)->generate($chain);

        $event = $chain->events()->first();
        $this->assertEquals('2099-07-01 14:30:00', $event->start_datetime->format('Y-m-d H:i:s'));
    }

    public function test_generator_creates_custom_content_when_custom_body_is_set(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create([
            'recurrence_type' => 'daily',
            'start_date' => '2099-07-01',
            'end_date' => '2099-07-01',
            'custom_body' => 'Session notes',
        ]);

        app(EventChainGeneratorService::class)->generate($chain);

        $event = $chain->events()->with('customContent')->first();
        $this->assertNotNull($event->customContent);
        $this->assertEquals('Session notes', $event->customContent->body);
    }

    public function test_generator_does_not_create_custom_content_when_custom_body_is_null(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create([
            'recurrence_type' => 'daily',
            'start_date' => '2099-07-01',
            'end_date' => '2099-07-01',
            'custom_body' => null,
        ]);

        app(EventChainGeneratorService::class)->generate($chain);

        $event = $chain->events()->with('customContent')->first();
        $this->assertNull($event->customContent);
    }

    public function test_generator_links_event_to_chain(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create([
            'recurrence_type' => 'daily',
            'start_date' => '2099-07-01',
            'end_date' => '2099-07-01',
        ]);

        app(EventChainGeneratorService::class)->generate($chain);

        $event = $chain->events()->first();
        $this->assertEquals($chain->id, $event->event_chain_id);
        $this->assertFalse($event->has_chain_conflict);
        $this->assertEquals([], $event->overridden_fields);
    }

    // ─── Updater: basic propagation ───────────────────────────────────────────

    public function test_updater_propagates_title_to_all_events(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create(['title' => 'Old Title']);
        Event::factory()->count(3)->create(['event_chain_id' => $chain->id, 'title' => 'Old Title']);

        app(EventChainUpdaterService::class)->update($chain, ['title' => 'New Title'], 'all');

        $this->assertEquals(3, $chain->events()->where('title', 'New Title')->count());
    }

    public function test_updater_returns_updated_count(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create();
        Event::factory()->count(4)->create(['event_chain_id' => $chain->id]);

        $result = app(EventChainUpdaterService::class)->update($chain, ['title' => 'Updated'], 'all');

        $this->assertEquals(4, $result['updated_count']);
    }

    public function test_updater_restricts_to_from_date_scope(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create(['title' => 'Old Title']);
        $past = Event::factory()->create([
            'event_chain_id' => $chain->id,
            'title' => 'Old Title',
            'start_datetime' => now()->subDays(10),
            'end_datetime' => now()->subDays(10)->addHours(2),
        ]);
        $future = Event::factory()->create([
            'event_chain_id' => $chain->id,
            'title' => 'Old Title',
            'start_datetime' => now()->addDays(10),
            'end_datetime' => now()->addDays(10)->addHours(2),
        ]);

        app(EventChainUpdaterService::class)->update(
            $chain, ['title' => 'New Title'], 'from_date', now()
        );

        $this->assertDatabaseHas('events', ['id' => $past->id, 'title' => 'Old Title']);
        $this->assertDatabaseHas('events', ['id' => $future->id, 'title' => 'New Title']);
    }

    public function test_updater_skips_and_flags_overridden_field(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create(['title' => 'Chain Title']);
        $event = Event::factory()->create([
            'event_chain_id' => $chain->id,
            'title' => 'Custom Title',
            'overridden_fields' => ['title'],
        ]);

        $result = app(EventChainUpdaterService::class)->update($chain, ['title' => 'New Title'], 'all');

        $event->refresh();
        $this->assertEquals('Custom Title', $event->title);
        $this->assertTrue($event->has_chain_conflict);
        $this->assertContains($event->id, $result['conflicted_event_ids']);
    }

    public function test_updater_ignores_non_propagatable_fields(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create();
        Event::factory()->create(['event_chain_id' => $chain->id]);

        $result = app(EventChainUpdaterService::class)->update(
            $chain, ['start_date' => '2099-01-01', 'end_date' => '2099-12-31'], 'all'
        );

        // Non-propagatable fields → nothing changed, no conflicts
        $this->assertEquals([], $result['conflicted_event_ids']);
    }

    // ─── Updater: conflict resolution ─────────────────────────────────────────

    public function test_resolve_conflict_accept_chain_updates_event_field(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create(['title' => 'Chain Title']);
        $event = Event::factory()->create([
            'event_chain_id' => $chain->id,
            'title' => 'Custom Title',
            'overridden_fields' => ['title'],
            'has_chain_conflict' => true,
        ]);

        app(EventChainUpdaterService::class)->resolveConflict($event, 'title', 'accept_chain', $chain);

        $event->refresh();
        $this->assertEquals('Chain Title', $event->title);
        $this->assertFalse($event->has_chain_conflict);
        $this->assertNotContains('title', $event->overridden_fields ?? []);
    }

    public function test_resolve_conflict_keep_override_preserves_event_field(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create(['title' => 'Chain Title']);
        $event = Event::factory()->create([
            'event_chain_id' => $chain->id,
            'title' => 'Custom Title',
            'overridden_fields' => ['title'],
            'has_chain_conflict' => true,
        ]);

        app(EventChainUpdaterService::class)->resolveConflict($event, 'title', 'keep_override', $chain);

        $event->refresh();
        $this->assertEquals('Custom Title', $event->title);
        // has_chain_conflict stays true: the event intentionally diverges from the chain
        $this->assertTrue($event->has_chain_conflict);
    }

    // ─── Event model helpers ──────────────────────────────────────────────────

    public function test_reset_to_chain_restores_all_chain_values(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create(['title' => 'Chain Title']);
        $event = Event::factory()->create([
            'event_chain_id' => $chain->id,
            'title' => 'Custom Title',
            'overridden_fields' => ['title'],
            'has_chain_conflict' => true,
            'pending_conflict_fields' => [],
        ]);

        app(EventChainUpdaterService::class)->resetToChain($event, $chain);

        $event->refresh();
        $this->assertEquals('Chain Title', $event->title);
        $this->assertEmpty($event->overridden_fields);
        $this->assertFalse($event->has_chain_conflict);
        $this->assertEmpty($event->pending_conflict_fields);
    }

    public function test_mark_field_overridden_adds_field(): void
    {
        $event = Event::factory()->create(['overridden_fields' => []]);

        $event->markFieldOverridden('title');

        $this->assertContains('title', $event->overridden_fields);
    }

    public function test_mark_field_overridden_is_idempotent(): void
    {
        $event = Event::factory()->create(['overridden_fields' => ['title']]);

        $event->markFieldOverridden('title');

        $this->assertCount(1, array_filter($event->overridden_fields, fn ($f) => $f === 'title'));
    }

    public function test_unmark_field_overridden_removes_field(): void
    {
        $event = Event::factory()->create(['overridden_fields' => ['title', 'location_id']]);

        $event->unmarkFieldOverridden('title');

        $this->assertNotContains('title', $event->overridden_fields);
        $this->assertContains('location_id', $event->overridden_fields);
    }

    public function test_detach_from_chain_clears_chain_fields(): void
    {
        $chain = EventChain::factory()->withoutEvents()->create();
        $event = Event::factory()->create([
            'event_chain_id' => $chain->id,
            'overridden_fields' => ['title'],
            'has_chain_conflict' => true,
        ]);

        $event->detachFromChain();

        $this->assertNull($event->event_chain_id);
        $this->assertNull($event->overridden_fields);
        $this->assertFalse($event->has_chain_conflict);
    }
}
